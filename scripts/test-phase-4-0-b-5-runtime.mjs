import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(path.join(process.cwd(),'package.json'));
const ts=require('typescript');
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'football-rich-b5-'));
for(const name of ['schema.ts','intake.ts']){const src=fs.readFileSync(path.join('src','data','v2',name),'utf8');const out=ts.transpileModule(src,{fileName:name,compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;fs.writeFileSync(path.join(temp,name.replace(/\\.ts$/,'.js')),out);}
fs.writeFileSync(path.join(temp,'package.json'),'{"type":"module"}');
const api=await import(pathToFileURL(path.join(temp,'intake.js')));
const envelope={format:'football-rich-data',schemaVersion:'2.0.0',exportedAt:'2026-11-17T10:00:00.000Z',sourceSystem:'FOOTBALL_TIME',targetSystem:'FOOTBALL_RICH',importType:'FIXTURE_UPDATE',batchId:'batch-1',recordCount:2,records:[{store:'matches',key:'m1',value:{localMatchId:'m1',homeTeamId:'t1',awayTeamId:'t2',kickoffAt:'2026-11-18T12:00:00.000Z',competitionId:'c1'}},{store:'teams',key:'t1',value:{teamId:'t1',nameNormalized:'home'}}]};
assert.equal(api.validateIntakeEnvelope(envelope).envelope.batchId,'batch-1');
assert.ok(api.validateIntakeEnvelope({...envelope,recordCount:1}).issues.some(x=>x.code==='RECORD_COUNT_MISMATCH'));
const preview=api.createIntakePreview(envelope);
assert.equal(preview.canCommit,true);assert.equal(preview.counts.add,2);
const dup=api.createIntakePreview(envelope,{matches:{m1:envelope.records[0].value}});
assert.equal(dup.counts.duplicate,1);
const version=api.createIntakePreview(envelope,{matches:{m1:{...envelope.records[0].value,kickoffAt:'2026-11-19T12:00:00.000Z'}}});
assert.equal(version.counts.versionRequired,1);
const blocked=api.createIntakePreview({...envelope,records:[{store:'matches',key:'m2',value:{localMatchId:'m2',homeTeamId:'t1',awayTeamId:'t1',kickoffAt:'2026-11-18T12:00:00.000Z',competitionId:'c1'}}],recordCount:1});
assert.equal(blocked.canCommit,false);
const coverage=api.assessIntakeCoverage('m1',envelope.records,'2026-11-17T10:00:00.000Z');
assert.equal(coverage.availableDomains,2);assert.equal(coverage.analysisReady,false);
fs.rmSync(temp,{recursive:true,force:true});
console.log('B.5 runtime tests passed: envelope validation, idempotent duplicate classification, version-required conflict handling, critical match validation, and honest coverage readiness.');
